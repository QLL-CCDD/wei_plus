#!/usr/bin/env node
import { spawn, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { checkNode, checkData } from './setup.mjs';
import { probePort, classifyAddresses } from './doctor.mjs';
const root = fileURLToPath(new URL('..', import.meta.url));
const ports = [Number(process.env.SP_CURRENT_PORT || 3000), Number(process.env.SP_LEGACY_PORT || 3001)];
const setupArgs = [];
let legacyPortSet = Boolean(process.env.SP_LEGACY_PORT);
let open = !/^(1|true|yes)$/i.test(process.env.SP_NO_BROWSER || '');
let prepare = true;
for (let i = 2; i < process.argv.length; i++) {
  const arg = process.argv[i];
  if (arg === '--help' || arg === '-h') {
    console.log('卫戍协议 wei_plus：首次自动安装依赖、下载素材并启动当前版与旧版。\n' +
      'node tools/start-versions.mjs [--port 3000] [--legacy-port 3001] [--no-open] [--no-setup]\n' +
      'setup 参数：--no-local、--local、--game <目录>、--no-assets、--yes、--quiet。Ctrl+C 停止。');
    process.exit(0);
  }
  if (arg === '--port' || arg === '--legacy-port') {
    const value = Number(process.argv[++i]);
    if (arg === '--port') { ports[0] = value; if (!legacyPortSet) ports[1] = value + 1; }
    else { ports[1] = value; legacyPortSet = true; }
  } else if (arg === '--host') process.env.HOST = process.argv[++i] || '0.0.0.0';
  else if (arg === '--no-open') open = false;
  else if (arg === '--no-setup') prepare = false;
  else if (arg === '--game') setupArgs.push(arg, process.argv[++i] || '');
  else setupArgs.push(arg);
}
if (!checkNode().ok) throw new Error('需要 Node.js 22/24：https://nodejs.org/zh-cn/download');
if (ports.some((p) => !Number.isInteger(p) || p < 1 || p > 65535) || ports[0] === ports[1]) throw new Error('Choose two distinct valid ports');
const ids = ['current', 'legacy'];
const probes = await Promise.all(ports.map((port) => probePort(port, process.env.HOST || '0.0.0.0')));
for (const [i, probe] of probes.entries()) {
  if (probe.state !== 'free' && !(probe.state === 'ours' && (probe.health.ruleset || 'current') === ids[i])) {
    throw new Error(`端口 ${ports[i]} 已被其他程序或另一版本占用，请使用 --port / --legacy-port 换端口。`);
  }
}
if (prepare && probes.some((probe) => probe.state === 'free')) {
  const setup = spawnSync(process.execPath, [join(root, 'tools/setup.mjs'), ...setupArgs], { cwd: root, stdio: 'inherit', windowsHide: true });
  if (setup.status !== 0) process.exit(setup.status || 1);
}
// Manifests can be regenerated by the asset downloader or optional local extraction.
// Reuse them without rebuilding the pinned historical game data.
for (const name of ['assets.json', 'emotes.json', 'local-assets.json']) {
  const source = join(root, 'data', name);
  if (fs.existsSync(source)) fs.copyFileSync(source, join(root, 'data/legacy', name));
}
const legacy = checkData(join(root, 'data/legacy'));
if (!legacy.ok) throw new Error(`旧版数据不完整，请重新下载仓库（缺少 ${legacy.missing.join(', ')}；无法解析 ${legacy.broken.join(', ')}）。`);
const children = [];
let stopping = false;
const stop = (code = 0) => {
  if (stopping) return;
  stopping = true;
  for (const child of children) if (child.exitCode == null) child.kill();
  process.exitCode = code;
};
for (const [i, id] of ids.entries()) {
  console.log(`${id === 'legacy' ? '旧版' : '当前版'}: http://localhost:${ports[i]}`);
  if (probes[i].state === 'ours') continue;
  const child = spawn(process.execPath, [join(root,'server/index.js')], {
    cwd:root, stdio:'inherit', windowsHide:true,
    env:{...process.env, PORT:String(ports[i]), SP_ALTERNATE_PORT:String(ports[1-i]),
      SP_DATA_DIR:join(root,'data',...(id==='legacy'?['legacy']:[]))},
  });
  children.push(child);
  child.on('error',(e)=>{console.error(e.message);stop(1);});
  child.on('exit',(code,signal)=>{if(!stopping) stop(code || (signal ? 1 : 0));});
}
process.on('SIGINT',()=>stop());
process.on('SIGTERM',()=>stop());
if (children.length) {
  const deadline = Date.now() + 30000;
  let ready = false;
  while (!stopping && Date.now() < deadline) {
    const health = await Promise.all(ports.map((port) => probePort(port)));
    ready = health.every((probe, i) => probe.state === 'ours' && (probe.health.ruleset || 'current') === ids[i]);
    if (ready) break;
    await new Promise((resolve) => setTimeout(resolve, 250));
  }
  if (!ready) { console.error('服务器未能启动，请查看上面的错误信息。'); stop(1); }
}
if (!stopping) {
  for (const address of classifyAddresses().filter((a) => ['lan', 'vpn', 'public'].includes(a.kind))) {
    console.log(`联机地址: http://${address.address}:${ports[0]} / http://${address.address}:${ports[1]}`);
  }
  console.log('登录页与大厅可切换版本。关闭窗口或 Ctrl+C 停止本窗口启动的服务器。');
  if (open) {
    const url = `http://localhost:${ports[0]}`;
    const platform = process.platform;
    const cmd = platform === 'win32' ? 'rundll32' : platform === 'darwin' ? 'open' : 'xdg-open';
    if (platform !== 'linux' || process.env.DISPLAY || process.env.WAYLAND_DISPLAY) {
      const browser = spawn(cmd, platform === 'win32' ? ['url.dll,FileProtocolHandler', url] : [url], { stdio: 'ignore', detached: true, windowsHide: true });
      browser.on('error', () => console.log(`请手动打开 ${url}`));
      browser.unref();
    }
  }
}
